def audio_mixer(lines):
    """The mixer and compressor of the MiSTer top, without the MT32-pi
    source, ending in audio_pre_l/r; AUDIO_MIX is done by AUDIO_STAGE."""
    mixer = '\n'.join(block(lines, 'wire signed [16:0] audio_opl2 =',
                            'hps_status[37:36] ? audio_cmp_r_q : audio_out_r_q;'))
    mixer = replace(mixer, '''    wire signed [16:0] audio_mt32_l_ext =
        {mt32_i2s_l[15], mt32_i2s_l};
    wire signed [16:0] audio_mt32_r_ext =
        {mt32_i2s_r[15], mt32_i2s_r};
    wire signed [16:0] audio_mt32_l = mt32_use ?
        {audio_mt32_l_ext[16], audio_mt32_l_ext[16:1]} : 17'sd0;
    wire signed [16:0] audio_mt32_r = mt32_use ?
        {audio_mt32_r_ext[16], audio_mt32_r_ext[16:1]} : 17'sd0;
''', '''    wire signed [16:0] audio_mt32_l = 17'sd0;     // no MT32-pi on the board
    wire signed [16:0] audio_mt32_r = 17'sd0;
''')
    mixer = replace(mixer, 'assign AUDIO_L      =', 'assign audio_pre_l =')
    mixer = replace(mixer, 'assign AUDIO_R      =', 'assign audio_pre_r =')
    return '    wire [15:0] audio_pre_l, audio_pre_r;\n' + mixer + '\n' + AUDIO_STAGE


def generate():
    lines = SOURCE.read_text().splitlines()
    out = [HEADER]

    # Status-derived options and AT286CTL.
    status = block(lines, 'wire [1:0]   at_monitor_profile_osd = hps_status[45:44];',
                   'wire [7:0] at286ctl_cpu;', include_end=False)
    status = [l for l in status if 'info' not in l and 'at_monitor_profile_pending' not in l
              and 'at_monitor_profile_osd != at_monitor_profile_applied' not in l]
    out += status
    out += block(lines, 'wire [7:0] at286ctl_cpu;', '.status_osd_match(at286ctl_status_osd_match)')
    out += ['    );']
    out.append(MIST_IO)

    # MIDI/UART baud enables.
    out += block(lines, 'logic [1:0]  midi_baud_div_q;', 'wire        physical_idle;', include_end=False)

    # Memory path: SDRAM pins, ROM loader, memory port, buffers.
    memory = '\n'.join(block(lines, 'wire        physical_idle;', '`ifdef PCAT286_RAM_DDR3',
                             include_end=False))
    oddr = '''    ODDR #(.DDR_CLK_EDGE("SAME_EDGE"), .INIT(1'b0), .SRTYPE("SYNC")) sdram_clock_ddr (
        .Q(SDRAM_CLK), .C(CLK_50M), .CE(1'b1), .D1(1'b1), .D2(1'b0), .R(1'b0), .S(1'b0)
    );'''
    altddio = memory[memory.index('    altddio_out #('):memory.index('    );', memory.index('    altddio_out #(')) + 6]
    memory = replace(memory, altddio, oddr)
    memory = replace(memory, '''    assign hps_status_menumask = {10'd0, at_bios_missing_ega, at_bios_missing_main,
                                  (`ENABLE_MIDI && mt32_available && at286ctl_eff_mpu401),
                                  3'b111};''', '')
    out.append(memory)
    out += block(lines, 'spk286_at_mister_sdram_owner u_at_sdram_owner (', '    );')

    # Timers and the keyboard controller front end.
    out += block(lines, 'logic counter_clock;', 'wire keyboard_event_overflow;')
    out.append(CLOCKS)
    out.append(KEYS)
    out += block(lines, 'spk286_at_keyboard u_at_keyboard (', '    );')
    out.append(HOLDS)
    out += block(lines, 'ega_monitor_profile_latch at_monitor_profile_latch (', '    );')

    # Video pipeline resets, raw video, option CDC, the machine.
    # at_video_vb_pipe_q is used by the option CDC before the MiSTer top
    # declares it with the other pipeline registers; declare it first here.
    out.append('    logic       at_video_vb_pipe_q;')
    pipe = '\n'.join(block(lines, 'wire at_cpu_reset_request;', 'spk286_at_machine #(', include_end=False))
    pipe = replace(pipe, '.clk_sys(CLK_50M), .src_idle(!HPS_BUS[34]),', '.clk_sys(CLK_50M), .src_idle(1\'b1),')
    out.append(pipe)
    out += block(lines, 'spk286_at_machine #(', '.at286ctl_sync          (at286ctl_sync)')
    out += ['    );']

    # 57 MHz pipeline and the monochrome converter.
    regs = block(lines, '    logic       at_video_dot_d_q;', 'wire [7:0] at_video_mono_r;', include_end=False)
    out += [line for line in regs if line != '    logic       at_video_vb_pipe_q;']
    out += block(lines, 'wire [7:0] at_video_mono_r;', '.VBlank_OUT (at_video_mono_vb)')
    out += ['    );']
    out.append(audio_mixer(lines))
    out.append(VIDEO_OUT)
    return '\n'.join(out) + '\n'


def main():
    text = generate()
    if sys.argv[1:] == ['--check']:
        if TARGET.read_text() != text:
            sys.exit(f'{TARGET.relative_to(ROOT)} is stale: run zxtres/scripts/make_guest.py')
        print('GUEST_CHECK_PASS')
        return
    TARGET.write_text(text)
    print(f'wrote {TARGET.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
