#!/usr/bin/env python3
"""Generate zxtres/rtl/pcat286_zxtres_guest.sv from the MiSTer top.

  make_guest.py [--check]

The ZXTRES guest keeps the board-independent parts of PCAT-286.sv verbatim
and replaces only the MiSTer glue:

- hps_io and hps_ext become MiST user_io and data_io;
- the DDR3 framebuffer and backend are dropped;
- the Quartus PLL and DDR output become an MMCM and an ODDR;
- the MiSTer video shell becomes a MiST OSD and a VGA output;
- MT32-pi, the UARTs and the HPS info notices are left out.

The kept parts are:

- the status word layout, rebuilt from the 64 MiST status bits;
- AT286CTL;
- the memory path from the CPU to the SDRAM;
- the ROM loader;
- the AT machine;
- the EGA pipeline into the monochrome converter.

Each kept block is located by a unique marker line, so a change to the
MiSTer top that moves or removes one stops the generator rather than
producing a silently different guest. With --check the generated text is
compared with the committed file.
"""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'PCAT-286.sv'
TARGET = ROOT / 'zxtres/rtl/pcat286_zxtres_guest.sv'


def block(lines, start, end, include_end=True):
    """Lines from the unique line containing START to the first line after
    it containing END."""
    starts = [i for i, line in enumerate(lines) if start in line]
    if len(starts) != 1:
        sys.exit(f'marker {start!r}: {len(starts)} matches in {SOURCE.name}')
    first = starts[0]
    for i in range(first + 1, len(lines)):
        if end in lines[i]:
            return lines[first:i + 1 if include_end else i]
    sys.exit(f'end marker {end!r} not found after {start!r}')


def replace(text, old, new, count=1):
    if text.count(old) != count:
        sys.exit(f'expected {count} of {old!r}, found {text.count(old)}')
    return text.replace(old, new)


HEADER = r'''// GENERATED by zxtres/scripts/make_guest.py from PCAT-286.sv. Do not edit:
// change the MiSTer top or the generator, then regenerate.
//
// PCAT-286 guest core for DeMiSTify on the ZXTRES+ (MiST interface). The AT
// machine, its memory path to the SDRAM and the EGA pipeline are the MiSTer
// core's own blocks; the MiSTer HPS glue is replaced by MiST user_io/data_io,
// a MiST OSD over the VGA output and the ZXTRES PS/2 keyboard.
//
// Not yet ported (zxtres/PORT.md): disks (the MiSTer management bus is tied
// off), audio output, MIDI/UARTs, the 350-line framebuffer for 15 kHz TVs.
`timescale 1ns/1ps

`ifndef ENABLE_OPL2
`define ENABLE_OPL2 1
`endif
`ifndef ENABLE_CMS
`define ENABLE_CMS 1
`endif
`ifndef ENABLE_TANDY_AUDIO
`define ENABLE_TANDY_AUDIO 1
`endif
`ifndef ENABLE_MIDI
`define ENABLE_MIDI 0
`endif
`ifndef ENABLE_SB
`define ENABLE_SB 1
`endif

module pcat286_zxtres_guest (
    input  logic        CLOCK_50,       // 50 MHz from a global buffer
    input  logic        RESET_N,        // from the DeMiSTify controller
    output logic        LED,

    output logic [12:0] SDRAM_A,
    inout  wire  [15:0] SDRAM_DQ,
    output logic        SDRAM_DQML,
    output logic        SDRAM_DQMH,
    output logic        SDRAM_nWE,
    output logic        SDRAM_nCAS,
    output logic        SDRAM_nRAS,
    output logic        SDRAM_nCS,
    output logic [1:0]  SDRAM_BA,
    output logic        SDRAM_CLK,
    output logic        SDRAM_CKE,

    output wire         SPI_DO,
    input  logic        SPI_DI,
    input  logic        SPI_SCK,
    input  logic        SPI_SS2,
    input  logic        SPI_SS3,
    input  logic        SPI_SS4,
    input  logic        CONF_DATA0,

    output logic [7:0]  VGA_R,
    output logic [7:0]  VGA_G,
    output logic [7:0]  VGA_B,
    output logic        VGA_HS,
    output logic        VGA_VS,

    input  logic        PS2K_CLK_IN,    // physical keyboard, blocked while the OSD is open
    input  logic        PS2K_DAT_IN,
    input  logic        PS2M_CLK_IN,    // physical mouse
    input  logic        PS2M_DAT_IN,
    output logic        PS2M_CLK_OUT,   // open collector: 0 pulls the line low
    output logic        PS2M_DAT_OUT,

    output logic [15:0] DAC_L,
    output logic [15:0] DAC_R
);
    wire CLK_50M = CLOCK_50;
    // Core reset: the controller's reset; status bit 0 (OSD reset and the
    // firmware's hold while it loads the ROMs) resets the machine below.
    wire RESET = !RESET_N;

    // ------------------------------------------------------------------
    // OSD. Status bits keep the MiSTer core's positions where they fit in
    // the 64 MiST bits; the fields above bit 63 move to free bits and are
    // put back in place in hps_status below.
    //   0 reset, 14-16 display, 23-27 joysticks, 28-29 220h audio,
    //   32-33 speaker volume, 42-43 OPL2, 44-45 monitor, 54 joystick swap,
    //   55 Tandy, 57-59 CPU speed, 30-31 + 53 installed RAM, 5 SB IRQ.
    // Option bits use the MiST digit form the DeMiSTify firmware parses
    // (CONFIG_STATUSWORD_64BIT): 0-9, then A-Z for 10-35, a-z for 36-61,
    // low bit first; it does not read the MiSTer O[high:low] form.
    localparam CONF_STR = {
        "PCAT286;;",
        "Ovx,CPU Speed,MAX,6 MHz,8 MHz,10 MHz,12.5 MHz,16 MHz,20 MHz,25 MHz;",
        "Oij,Monitor,5153/CGA,5154/ECD,5151/MDA;",
        "OEG,Display,Full Color,Green,Amber,B&W,Red,Blue,Fuchsia,Purple;",
        "Orr,Installed RAM,4MB,1MB;",
        "OST,Audio 220h,C/MS,Sound Blaster,Disabled;",
        "Ogh,OPL2,Adlib 388h,SB FM 388h/228h,Disabled;",
        "Ott,Tandy Sound,Disabled,Enabled;",
        "ONO,Joystick 1,Analog,Digital,Disabled;",
        "OPQ,Joystick 2,Analog,Digital,Disabled;",
        "T0,Reset;",
        "V,v0.1"
    };

    logic [63:0] status;
    logic [31:0] joystick_0, joystick_1;
    // MiSTer status layout for the verbatim blocks. The monitor choice is
    // reordered so the first OSD entry, the 31 kHz-capable 5153/CGA, is the
    // default; MiSTer order is 5154/ECD, 5153/CGA, 5151/MDA.
    wire [1:0] monitor_osd = status[45:44] == 2'd0 ? 2'd1 :
                             status[45:44] == 2'd1 ? 2'd0 : 2'd2;
    // Machine resets, registered further down; the verbatim blocks use
    // them before that point.
    logic at_boot_reset = 1'b1;
    logic at_machine_reset = 1'b1;

    wire [127:0] hps_status;
    assign hps_status[63:0] = {status[63:46], monitor_osd, status[43:0]};
    assign hps_status[66:64] = 3'd0;                  // VSync width: auto
    assign hps_status[69:67] = 3'd0;                  // HSync width: auto
    assign hps_status[70] = status[5];                // SB IRQ 5/7
    assign hps_status[71] = 1'b0;
    assign hps_status[74:72] = status[53] ? 3'd3 : 3'd0;   // 1 MB : 4 MB
    assign hps_status[77:75] = status[59:57];
    assign hps_status[127:78] = '0;
    wire [1:0] hps_buttons = 2'b00;
    wire [15:0] joystick_l_analog_0 = 16'h0000;   // no analog joysticks on DB9
    wire [15:0] joystick_l_analog_1 = 16'h0000;
'''

MIST_IO = r'''
    // ------------------------------------------------------------------
    // MiST interface on the 50 MHz clock.
    /* verilator lint_off PINCONNECTEMPTY */
    user_io #(.STRLEN($size(CONF_STR) >> 3), .PS2DIV(2000)) u_user_io (
        .conf_str(CONF_STR), .conf_addr(), .conf_chr(8'h00),
        .clk_sys(CLK_50M), .clk_sd(CLK_50M),
        .SPI_CLK(SPI_SCK), .SPI_SS_IO(CONF_DATA0), .SPI_MISO(SPI_DO), .SPI_MOSI(SPI_DI),
        .joystick_0(joystick_0), .joystick_1(joystick_1), .joystick_2(), .joystick_3(),
        .joystick_4(), .joystick_analog_0(), .joystick_analog_1(),
        .buttons(), .switches(), .scandoubler_disable(), .ypbpr(), .no_csync(),
        .status(status), .core_mod(), .rtc(),
        .sd_lba(32'd0), .sd_cnt(8'd0), .sd_rd(2'b00), .sd_wr(2'b00), .sd_ack(), .sd_ack_conf(),
        .sd_ack_x(), .sd_conf(1'b0), .sd_sdhc(1'b1), .sd_dout(), .sd_dout_strobe(),
        .sd_din(8'h00), .sd_din_strobe(), .sd_buff_addr(), .img_mounted(), .img_size(),
        .ps2_kbd_clk(), .ps2_kbd_data(), .ps2_kbd_clk_i(1'b1), .ps2_kbd_data_i(1'b1),
        .ps2_mouse_clk(), .ps2_mouse_data(), .ps2_mouse_clk_i(1'b1), .ps2_mouse_data_i(1'b1),
        .key_pressed(), .key_extended(), .key_code(), .key_strobe(),
        .kbd_out_data(8'h00), .kbd_out_strobe(1'b0), .leds(8'h00),
        .mouse_x(), .mouse_y(), .mouse_z(), .mouse_flags(), .mouse_strobe(), .mouse_idx(),
        .i2c_start(), .i2c_read(), .i2c_addr(), .i2c_subaddr(), .i2c_dout(),
        .i2c_din(8'h00), .i2c_ack(1'b0), .i2c_end(1'b0),
        .serial_data(8'h00), .serial_strobe(1'b0)
    );

    wire        ioctl_download;
    wire [7:0]  ioctl_index_mist;
    wire [15:0] ioctl_index = {8'h00, ioctl_index_mist};
    wire        ioctl_wr;
    wire [26:0] ioctl_addr;
    wire [15:0] ioctl_data;
    // MiST data_io has no wait input; the loader writes each word to SDRAM
    // long before the next arrives over SPI (see zxtres/PORT.md).
    wire        ioctl_wait;
    data_io #(.DOUT_16(1'b1)) u_data_io (
        .clk_sys(CLK_50M), .SPI_SCK(SPI_SCK), .SPI_SS2(SPI_SS2), .SPI_SS4(SPI_SS4),
        .SPI_DI(SPI_DI), .QCSn(1'b1), .QSCK(1'b1), .QDAT(4'hF), .clkref_n(1'b0),
        .ioctl_download(ioctl_download), .ioctl_upload(), .ioctl_index(ioctl_index_mist),
        .ioctl_wr(ioctl_wr), .ioctl_addr(ioctl_addr), .ioctl_dout(ioctl_data),
        .ioctl_din(8'h00), .ioctl_fileext(), .ioctl_filesize(),
        .hdd_clk(CLK_50M), .hdd_cmd_req(1'b0), .hdd_cdda_req(1'b0), .hdd_dat_req(1'b0),
        .hdd_cdda_wr(), .hdd_status_wr(), .hdd_addr(), .hdd_wr(), .hdd_data_out(),
        .hdd_data_in(16'h0000), .hdd_data_rd(), .hdd_data_wr(), .hdd0_ena(), .hdd1_ena()
    );
    /* verilator lint_on PINCONNECTEMPTY */

    // Physical PS/2 keyboard to the MiSTer ps2_key event format.
    wire [7:0]  kbd_byte;
    wire        kbd_strobe;
    wire [10:0] ps2_key;
    zxtres_ps2_rx u_kbd_rx (
        .clk(CLK_50M), .reset(RESET), .ps2_clk(PS2K_CLK_IN), .ps2_data(PS2K_DAT_IN),
        .data(kbd_byte), .strobe(kbd_strobe), .error()
    );
    zxtres_ps2_key u_kbd_events (
        .clk(CLK_50M), .reset(RESET), .byte_valid(kbd_strobe), .byte_in(kbd_byte),
        .ps2_key(ps2_key)
    );

    // Disks are not ported yet: the MiSTer management bus stays idle, so the
    // BIOS finds no floppy or hard disk.
    wire [15:0] at_mgmt_din;
    wire [15:0] at_mgmt_dout = 16'h0000;
    wire [15:0] at_mgmt_address = 16'h0000;
    wire        at_mgmt_read = 1'b0;
    wire        at_mgmt_write = 1'b0;
    wire [1:0]  at_floppy_present;
    wire [1:0]  at_floppy_request;
    wire [2:0]  at_ide_request;
    wire [1:0]  at_use_mmc_q = 2'b00;

    // Serial mouse on COM1 (Microsoft protocol) from the PS/2 mouse port.
    wire uart1_rx;
    wire uart1_rts_n;
    wire ps2_mouse_clk_drive, ps2_mouse_data_drive;
    MSMouseWrapper #(.CLKFREQ(50_000_000)) u_serial_mouse (
        .clk          (CLK_50M),
        .ps2dta_in    (PS2M_DAT_IN),
        .ps2clk_in    (PS2M_CLK_IN),
        .ps2dta_out   (ps2_mouse_data_drive),
        .ps2clk_out   (ps2_mouse_clk_drive),
        .rts          (~uart1_rts_n),
        .rd           (uart1_rx)
    );
    assign PS2M_CLK_OUT = ps2_mouse_clk_drive;
    assign PS2M_DAT_OUT = ps2_mouse_data_drive;

    // COM2 and MIDI are not wired on this board yet; idle receive lines.
    wire midi_rx = 1'b1;
    wire midi_tx;
    wire uart2_rx = 1'b1;
    wire uart2_cts_n = 1'b1;
    wire uart2_dsr_n = 1'b1;
    wire uart2_dcd_n = 1'b1;
    wire uart2_tx;
    wire uart2_rts_n;
    wire uart2_dtr_n;
'''

CLOCKS = r'''
    // Video clocks as the MiSTer pll_system: 28.636 MHz EGA dots and the
    // 57.272 MHz pipeline (630 MHz VCO / 22 and / 11).
    wire at_video_clk_28;
    wire at_video_clk_57_ps;
    wire at_video_pll_locked;
    wire video_feedback, video_clk_28_mmcm, video_clk_57_mmcm;
    /* verilator lint_off PINCONNECTEMPTY */
    MMCME2_BASE #(
        .CLKIN1_PERIOD(20.0),
        .DIVCLK_DIVIDE(5),
        .CLKFBOUT_MULT_F(63.0),          // VCO 630 MHz
        .CLKOUT0_DIVIDE_F(22.0),         // 28.636 MHz
        .CLKOUT1_DIVIDE(11)              // 57.273 MHz
    ) u_video_mmcm (
        .CLKIN1(CLK_50M), .CLKFBIN(video_feedback), .CLKFBOUT(video_feedback),
        .CLKOUT0(video_clk_28_mmcm), .CLKOUT1(video_clk_57_mmcm),
        .CLKOUT0B(), .CLKOUT1B(), .CLKOUT2(), .CLKOUT2B(), .CLKOUT3(), .CLKOUT3B(),
        .CLKOUT4(), .CLKOUT5(), .CLKOUT6(), .CLKFBOUTB(),
        .LOCKED(at_video_pll_locked), .PWRDWN(1'b0), .RST(1'b0)
    );
    /* verilator lint_on PINCONNECTEMPTY */
    BUFG u_video_28_bufg (.I(video_clk_28_mmcm), .O(at_video_clk_28));
    BUFG u_video_57_bufg (.I(video_clk_57_mmcm), .O(at_video_clk_57));
    // The MiSTer output stage used a phase-shifted copy; VGA here is
    // registered on the pipeline clock itself.
    assign at_video_clk_57_ps = at_video_clk_57;

    // The machine resets are registered, so that they enter the machine
    // from a flip-flop rather than through the loader and status decode;
    // otherwise they head the longest clk50 paths on the Artix-7.
    always_ff @(posedge CLK_50M)
        at_boot_reset <= RESET | hps_status[0] | hps_buttons[1] |
                         !main_rom_loaded | !at_video_pll_locked;
    wire at_video_output_reset = RESET | hps_status[0] | hps_buttons[1] |
                                 !at_video_pll_locked;
'''

HOLDS = r'''
    // No boot splash and no HPS info notices on this board.
    wire at_splashscreen = 1'b0;
    wire at_splash_boot_hold = 1'b0;
    wire at_bios_hold = 1'b0;

    always_ff @(posedge CLK_50M)
        at_machine_reset <= at_boot_reset | at_splash_boot_hold |
                            at_bios_required_missing | at_bios_hold;
'''

VIDEO_OUT = r'''
    // ------------------------------------------------------------------
    // DeMiSTify OSD over the EGA/VGA picture, then the VGA connector.
    wire [5:0] osd_r, osd_g, osd_b;
    /* verilator lint_off PINCONNECTEMPTY */
    osd #(.OSD_AUTO_CE(1'b0), .USE_BLANKS(1'b1), .OUT_COLOR_DEPTH(6)) u_osd (
        .clk_sys(at_video_clk_57), .ce(at_video_ce_pipe_q),
        .SPI_SCK(SPI_SCK), .SPI_SS3(SPI_SS3), .SPI_DI(SPI_DI),
        .rotate(2'b00),
        .R_in(at_video_mono_r[7:2]), .G_in(at_video_mono_g[7:2]), .B_in(at_video_mono_b[7:2]),
        .HBlank(at_video_mono_hb), .VBlank(at_video_mono_vb),
        .HSync(at_video_mono_hs), .VSync(at_video_mono_vs),
        .R_out(osd_r), .G_out(osd_g), .B_out(osd_b),
        .osd_enable()
    );
    /* verilator lint_on PINCONNECTEMPTY */

    // video_ce/video_de mark the dots of the picture for simulation capture.
    logic video_ce, video_de;
    always_ff @(posedge at_video_clk_57) begin
        if (at_video_pipe_reset_57) begin
            {VGA_R, VGA_G, VGA_B} <= '0;
            VGA_HS <= 1'b1;
            VGA_VS <= 1'b1;
            video_ce <= 1'b0;
            video_de <= 1'b0;
        end else begin
            VGA_R <= at_video_mono_hb | at_video_mono_vb ? 8'h00 : {osd_r, osd_r[5:4]};
            VGA_G <= at_video_mono_hb | at_video_mono_vb ? 8'h00 : {osd_g, osd_g[5:4]};
            VGA_B <= at_video_mono_hb | at_video_mono_vb ? 8'h00 : {osd_b, osd_b[5:4]};
            VGA_HS <= at_video_mono_hs;
            VGA_VS <= at_video_mono_vs;
            video_ce <= at_video_ce_pipe_q;
            video_de <= !(at_video_mono_hb | at_video_mono_vb);
        end
    end

    assign LED = main_rom_loaded;
    // Audio output is milestone 4 (zxtres/PORT.md).
    assign DAC_L = '0;
    assign DAC_R = '0;

    /* verilator lint_off UNUSEDSIGNAL */
    wire unused = &{1'b0, joystick_0[31:14], joystick_1[31:14], midi_tx, uart2_tx,
                    uart2_rts_n, uart2_dtr_n, at_floppy_present, at_floppy_request,
                    at_ide_request, at_mgmt_din, cpu_fault, machine_protocol_error,
                    keyboard_event_overflow, at_video_scale_q, at_video_arx_q, at_video_ary_q};
    /* verilator lint_on UNUSEDSIGNAL */
endmodule
'''


def generate():
    lines = SOURCE.read_text().splitlines()
    out = [HEADER]

    # Status-derived options and AT286CTL.
    status = block(lines, 'wire [1:0]   at_monitor_profile_osd = hps_status[45:44];',
                   'wire [7:0] at286ctl_cpu;', include_end=False)
    status = [l for l in status if 'info' not in l and 'at_monitor_profile_pending' not in l
              and 'at_monitor_profile_osd != at_monitor_profile_applied' not in l]
    out += status
    out += block(lines, 'wire [7:0] at286ctl_cpu;', '.status_osd_match(at286ctl_status_osd_match)')
    out += ['    );']
    out.append(MIST_IO)

    # MIDI/UART baud enables.
    out += block(lines, 'logic [1:0]  midi_baud_div_q;', 'wire        physical_idle;', include_end=False)

    # Memory path: SDRAM pins, ROM loader, memory port, buffers.
    memory = '\n'.join(block(lines, 'wire        physical_idle;', '`ifdef PCAT286_RAM_DDR3',
                             include_end=False))
    oddr = '''    ODDR #(.DDR_CLK_EDGE("SAME_EDGE"), .INIT(1'b0), .SRTYPE("SYNC")) sdram_clock_ddr (
        .Q(SDRAM_CLK), .C(CLK_50M), .CE(1'b1), .D1(1'b1), .D2(1'b0), .R(1'b0), .S(1'b0)
    );'''
    altddio = memory[memory.index('    altddio_out #('):memory.index('    );', memory.index('    altddio_out #(')) + 6]
    memory = replace(memory, altddio, oddr)
    memory = replace(memory, '''    assign hps_status_menumask = {10'd0, at_bios_missing_ega, at_bios_missing_main,
                                  (`ENABLE_MIDI && mt32_available && at286ctl_eff_mpu401),
                                  3'b111};''', '')
    out.append(memory)
    out += block(lines, 'spk286_at_mister_sdram_owner u_at_sdram_owner (', '    );')

    # Timers and the keyboard controller front end.
    out += block(lines, 'logic counter_clock;', 'wire keyboard_event_overflow;')
    out.append(CLOCKS)
    out += block(lines, 'spk286_at_keyboard u_at_keyboard (', '    );')
    out.append(HOLDS)
    out += block(lines, 'ega_monitor_profile_latch at_monitor_profile_latch (', '    );')

    # Video pipeline resets, raw video, option CDC, the machine.
    # at_video_vb_pipe_q is used by the option CDC before the MiSTer top
    # declares it with the other pipeline registers; declare it first here.
    out.append('    logic       at_video_vb_pipe_q;')
    pipe = '\n'.join(block(lines, 'wire at_cpu_reset_request;', 'spk286_at_machine #(', include_end=False))
    pipe = replace(pipe, '.clk_sys(CLK_50M), .src_idle(!HPS_BUS[34]),', '.clk_sys(CLK_50M), .src_idle(1\'b1),')
    out.append(pipe)
    out += block(lines, 'spk286_at_machine #(', '.at286ctl_sync          (at286ctl_sync)')
    out += ['    );']

    # 57 MHz pipeline and the monochrome converter.
    regs = block(lines, '    logic       at_video_dot_d_q;', 'wire [7:0] at_video_mono_r;', include_end=False)
    out += [line for line in regs if line != '    logic       at_video_vb_pipe_q;']
    out += block(lines, 'wire [7:0] at_video_mono_r;', '.VBlank_OUT (at_video_mono_vb)')
    out += ['    );']
    out.append(VIDEO_OUT)
    return '\n'.join(out) + '\n'


def main():
    text = generate()
    if sys.argv[1:] == ['--check']:
        if TARGET.read_text() != text:
            sys.exit(f'{TARGET.relative_to(ROOT)} is stale: run zxtres/scripts/make_guest.py')
        print('GUEST_CHECK_PASS')
        return
    TARGET.write_text(text)
    print(f'wrote {TARGET.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
