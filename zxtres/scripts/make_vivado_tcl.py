#!/usr/bin/env python3
"""Write the Tcl scripts that create the Vivado project, from a build directory.

  make_vivado_tcl.py BUILD_DIR PART_A100T PART_A200T DEFINE...

BUILD_DIR is the one build_pcat.sh prepares (vhdl_sources.txt, sv_sources.txt,
include_dirs.txt, osd_font.mem). The output goes to zxtres/vivado:

  create_project.tcl         the project, with every source listed
  create_project_A100T.tcl   the ZXTRES+  (a few lines that call the above)
  create_project_A200T.tcl   the ZXTRES++
  generated/                 the files the build makes: the controller ROMs,
                             the OSD font memory and the default_nettype helper

They run inside Vivado, on any host, with `source`: no bash, WSL or Python is
needed to create the project. build_pcat.sh runs this on every build, so the
files stay up to date; commit them when git shows them changed.
"""
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'zxtres' / 'vivado'
GEN = OUT / 'generated'


def lines(path):
    return [line.strip() for line in Path(path).read_text().splitlines() if line.strip()]


def repo_path(entry):
    """Repository-relative path of a build-directory entry (src/<path>)."""
    path = entry[len('src/'):]
    name = Path(path).name
    if path.startswith('build/zxtres-pcat/firmware/') or name == 'zxtres_nettype_wire.sv':
        source = ROOT / path if path.startswith('build/') else BUILD / entry
        shutil.copyfile(source, GEN / name)
        return f'zxtres/vivado/generated/{name}'
    return path


def tcl_list(items):
    return '\n'.join(f'    {{{item}}} \\' for item in items)


BUILD = Path(sys.argv[1]).resolve()
part_a100t, part_a200t, defines = sys.argv[2], sys.argv[3], sys.argv[4:]
GEN.mkdir(parents=True, exist_ok=True)
vhdl = [repo_path(e) for e in lines(BUILD / 'vhdl_sources.txt')]
sv = [repo_path(e) for e in lines(BUILD / 'sv_sources.txt')]
includes = [e[len('src/'):] if e != 'src' else '.' for e in lines(BUILD / 'include_dirs.txt')]
shutil.copyfile(BUILD / 'osd_font.mem', GEN / 'osd_font.mem')
memories = ['zxtres/vivado/generated/osd_font.mem', 'rtl/common/font0.hex',
            'rtl/video/splash_vga_palette.hex', 'zxtres/splash/splash_vga_320x200.hex',
            'zxtres/credits/msg.bin']

(OUT / 'create_project.tcl').write_bytes(f'''# Create the Vivado project for PCAT-286 on the ZXTRES+ or the ZXTRES++.
# Generated by zxtres/scripts/make_vivado_tcl.py (build_pcat.sh ... project):
# do not edit; change the sources and generate it again.
#
# In Vivado, on any host: Tools > Run Tcl Script, or in the Tcl console
#   source <repository>/zxtres/vivado/create_project_A100T.tcl   (ZXTRES+)
#   source <repository>/zxtres/vivado/create_project_A200T.tcl   (ZXTRES++)
# The project is created in zxtres/vivado/project-<board> and opened. The
# DeMiSTify and mist-modules submodules must be checked out.
if {{![info exists pcat_board]}} {{ set pcat_board A100T }}
switch -- $pcat_board {{
    A100T {{ set part {part_a100t} }}
    A200T {{ set part {part_a200t} }}
    default {{ error "pcat_board must be A100T or A200T" }}
}}
set here [file dirname [file normalize [info script]]]
set root [file normalize [file join $here .. ..]]
set top zxtres_pcat_top

set vhdl [list \
{tcl_list(vhdl)}
]
set sv [list \
{tcl_list(sv)}
]
set memories [list \
{tcl_list(memories)}
]
set includes [list \
{tcl_list(includes)}
]
set defines [list {' '.join(defines)}]

proc absolute {{paths}} {{
    global root
    set result {{}}
    foreach path $paths {{ lappend result [file normalize [file join $root $path]] }}
    return $result
}}
foreach check [concat $vhdl $sv $memories] {{
    if {{![file exists [file join $root $check]]}} {{
        error "missing $check (are the submodules checked out?)"
    }}
}}

set dir [file join $here project-$pcat_board]
create_project -force pcat286_zxtres $dir -part $part
# Keep the order of the lists: a file that ends with `default_nettype none is
# followed by a helper that restores it, as in the batch build.
set_property source_mgmt_mode DisplayOnly [current_project]
add_files -norecurse [absolute $vhdl]
set_property library work [get_files [absolute $vhdl]]
add_files -norecurse [absolute $sv]
set_property file_type SystemVerilog [get_files [absolute $sv]]
add_files -norecurse [absolute $memories]
add_files -fileset constrs_1 -norecurse [file join $root zxtres constraints zxtres_pcat.xdc]
set_property include_dirs [absolute $includes] [current_fileset]
set_property verilog_define $defines [current_fileset]
set_property top $top [current_fileset]

# The directives of the batch build (zxtres/scripts/build_pcat.tcl).
set impl [get_runs impl_1]
set_property STEPS.PLACE_DESIGN.ARGS.DIRECTIVE ExtraTimingOpt $impl
set_property STEPS.PHYS_OPT_DESIGN.IS_ENABLED true $impl
set_property STEPS.PHYS_OPT_DESIGN.ARGS.DIRECTIVE AggressiveExplore $impl
set_property STEPS.ROUTE_DESIGN.ARGS.DIRECTIVE AggressiveExplore $impl
set_property STEPS.POST_ROUTE_PHYS_OPT_DESIGN.IS_ENABLED true $impl
set_property STEPS.POST_ROUTE_PHYS_OPT_DESIGN.ARGS.DIRECTIVE AggressiveExplore $impl
puts "project: [file join $dir pcat286_zxtres.xpr]"
'''.replace('\r\n', '\n').encode())

for board in ('A100T', 'A200T'):
    (OUT / f'create_project_{board}.tcl').write_bytes(f'''# PCAT-286 project for the {'ZXTRES+' if board == 'A100T' else 'ZXTRES++'} ({board}). In Vivado: source this file.
set pcat_board {board}
source [file join [file dirname [file normalize [info script]]] create_project.tcl]
'''.encode())

print(f'wrote {OUT}')
